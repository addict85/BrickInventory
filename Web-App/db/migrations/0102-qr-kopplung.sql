-- QR-Anmeldung in zwei Schritten: Der Scan meldet nur ein Gerät an, den Zugang
-- gibt es erst, wenn die angemeldete Web-Sitzung es mit dem Code bestätigt, den
-- die App zeigt. Gespeichert sind nur Hashes von Abholgeheimnis und Code.
-- Offene Codes aus der Zeit davor gelten nicht weiter: Sie kennen keine Bestätigung.
DELETE FROM qr_login_tokens;
ALTER TABLE qr_login_tokens ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE qr_login_tokens ADD COLUMN IF NOT EXISTS abholung text;
ALTER TABLE qr_login_tokens ADD COLUMN IF NOT EXISTS code_hash text;
ALTER TABLE qr_login_tokens ADD COLUMN IF NOT EXISTS geraet text;
ALTER TABLE qr_login_tokens ADD COLUMN IF NOT EXISTS ip_bereich text;
ALTER TABLE qr_login_tokens ADD COLUMN IF NOT EXISTS fehlversuche integer NOT NULL DEFAULT 0;
ALTER TABLE qr_login_tokens ADD COLUMN IF NOT EXISTS bestaetigt_am timestamp with time zone;
ALTER TABLE qr_login_tokens ADD COLUMN IF NOT EXISTS abgelehnt_am timestamp with time zone;
ALTER TABLE qr_login_tokens ADD COLUMN IF NOT EXISTS abgeholt_am timestamp with time zone;
CREATE UNIQUE INDEX IF NOT EXISTS idx_qr_login_id ON qr_login_tokens (id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_qr_login_abholung ON qr_login_tokens (abholung) WHERE abholung IS NOT NULL;
