'use strict';
/**
 * The complete schema in one place: db/schema-snapshot.sql.
 */
const fs = require('node:fs');
const path = require('node:path');

const DATEI = path.join(__dirname, '..', 'db/schema-snapshot.sql');

/**
 * The text of the schema file from a connected database.
 * @param {{ all: (sql: string, werte?: unknown[]) => Promise<any[]> }} db
 * @returns {Promise<string>}
 */
async function schemaText(db) {
  const columns = await db.all(`
    SELECT c.relname AS tabelle, a.attname AS spalte, format_type(a.atttypid, a.atttypmod) AS typ,
           a.attnotnull AS pflicht, pg_get_expr(d.adbin, d.adrelid) AS vorgabe
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
      JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
      LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
     WHERE c.relkind IN ('r', 'p')
     ORDER BY c.relname, a.attnum`);
  const limits = await db.all(`
    SELECT conrelid::regclass::text AS tabelle, conname AS name, pg_get_constraintdef(oid) AS def
      FROM pg_constraint WHERE connamespace = 'public'::regnamespace AND conrelid <> 0
       AND contype <> 'n'  -- ab PG 18 stehen NOT NULL auch hier; die Spalte zeigt sie schon
     ORDER BY 1, 2`);
  const indexes = await db.all(`
    SELECT i.tablename AS tabelle, i.indexdef AS def FROM pg_indexes i
     WHERE i.schemaname = 'public'
       AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conname = i.indexname AND k.connamespace = 'public'::regnamespace)
     ORDER BY 1, i.indexname`);
  const trigger = await db.all(`
    SELECT tgrelid::regclass::text AS tabelle, pg_get_triggerdef(oid) AS def
      FROM pg_trigger WHERE NOT tgisinternal ORDER BY 1, tgname`);
  const functions = await db.all(`
    SELECT p.proname AS name, pg_get_functiondef(p.oid) AS def
      FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace AND n.nspname = 'public'
      LEFT JOIN pg_depend d ON d.objid = p.oid AND d.deptype = 'e'
     WHERE d.objid IS NULL ORDER BY 1, 2`);
  const extensions = await db.all(`SELECT extname FROM pg_extension WHERE extname <> 'plpgsql' ORDER BY 1`);
  const rowSecurity = await db.all(`
    SELECT c.relname AS tabelle, c.relforcerowsecurity AS zwang FROM pg_class c
     WHERE c.relnamespace = 'public'::regnamespace AND c.relrowsecurity ORDER BY 1`);
  const rules = await db.all(`
    SELECT tablename AS tabelle, policyname AS name, permissive, cmd, roles::text[] AS rollen, qual, with_check
      FROM pg_policies WHERE schemaname = 'public' ORDER BY 1, 2`);

  /** @param {any[]} rows @param {string} table */
  const fromValue = (rows, table) => rows.filter(z => z.tabelle === table);
  const tables = [...new Set(columns.map(s => s.tabelle))];
  const parts = [
    '-- Generated by scripts/schema-snapshot.js from a fresh database.',
    '-- Do not edit by hand and do not load: the schema arises from',
    '-- db/base.sql and db/migrations/. Regenerate with',
    '-- `npm run build && npm run schema:snapshot`.',
    '',
    ...extensions.map(e => `CREATE EXTENSION ${e.extname};`),
  ];
  for (const t of tables) {
    const rows = fromValue(columns, t).map(
      s => `  ${s.spalte} ${s.typ}${s.pflicht ? ' NOT NULL' : ''}${s.vorgabe != null ? ` DEFAULT ${s.vorgabe}` : ''}`,
    );
    rows.push(...fromValue(limits, t).map(k => `  CONSTRAINT ${k.name} ${k.def}`));
    parts.push('', `CREATE TABLE ${t} (`, rows.join(',\n'), ');');
    parts.push(...fromValue(indexes, t).map(i => `${i.def.replace(/ ON public\./, ' ON ')};`));
    parts.push(...fromValue(trigger, t).map(g => `${g.def.replace(/ ON public\./, ' ON ')};`));
    for (const z of fromValue(rowSecurity, t))
      parts.push(`ALTER TABLE ${t} ${z.zwang ? 'FORCE' : 'ENABLE'} ROW LEVEL SECURITY;`);
    parts.push(
      ...fromValue(rules, t).map(
        r =>
          `CREATE POLICY ${r.name} ON ${t}${r.permissive === 'PERMISSIVE' ? '' : ' AS RESTRICTIVE'}` +
          `${r.cmd === 'ALL' ? '' : ` FOR ${r.cmd}`}${r.rollen.join() === 'public' ? '' : ` TO ${r.rollen.join(', ')}`}` +
          `${r.qual ? ` USING (${r.qual})` : ''}${r.with_check ? ` WITH CHECK (${r.with_check})` : ''};`,
      ),
    );
  }
  for (const f of functions) parts.push('', `${f.def.trim()};`);
  return parts.join('\n').replace(/public\./g, '') + '\n';
}

const BASIS = path.join(__dirname, '..', 'db/base.sql');
/** Start data a new installation needs; everything else stays empty. */
const BASE_DATA = [
  'auftrag_exklusiv',
  'auftrags_arten',
  'global_settings',
  'gutschein_guthaben_schranke',
  'schema_migrations',
];

/** Major version of the pg_dump in the path; the copy differs between versions. */
function pgDumpVersion() {
  const { execFileSync } = require('node:child_process');
  return Number((execFileSync('pg_dump', ['--version'], { encoding: 'utf8' }).match(/\) (\d+)\./) || [])[1]) || null;
}

/**
 * The text of db/base.sql from a database: schema and start data as
 * executable SQL, without pg_dump's intermediate headings. Needs pg_dump in the path.
 * @param {string} url
 */
function basisText(url) {
  const { execFileSync } = require('node:child_process');
  /** @param {string[]} args */
  const dump = args =>
    execFileSync('pg_dump', [...args, '--no-owner', '--no-privileges', '--no-comments', url], {
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    });
  const raw =
    dump(['--schema-only']) +
    '\n' +
    dump(['--data-only', '--column-inserts', ...BASE_DATA.flatMap(t => ['-t', `public.${t}`])]);
  // Away with it: psql commands (\restrict), the clearing of the search path (the trigger functions
  // look for their tables without a schema prefix), version lines and the heading per object.
  const clean = raw
    .split('\n')
    .filter(
      z =>
        !/^\\(un)?restrict\b/.test(z) &&
        !/^SELECT pg_catalog\.set_config\('search_path'/.test(z) &&
        !/^--( Dumped (from|by).*| (Data for )?Name: .*| PostgreSQL database dump( complete)?)?$/.test(z),
    )
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return (
    [
      '-- Schema of a NEW installation: image of all migrations that existed at',
      '-- its creation. db/database.ts loads it into an empty database,',
      '-- after that only the younger migrations run. Do not edit by hand —',
      '-- regenerate with `npm run build && npm run schema:snapshot`.',
      `-- Generated with pg_dump ${pgDumpVersion()}.`,
      '',
    ].join('\n') +
    clean +
    '\n'
  );
}

/** Write db/base.sql from a fully migrated database. @param {string} url */
function writeBase(url) {
  fs.writeFileSync(BASIS, basisText(url));
  console.log(`geschrieben: ${path.relative(process.cwd(), BASIS)}`);
}

/** Create a fresh database, build it, describe it, delete it again. */
async function main() {
  const basis = process.env.DATABASE_URL;
  if (!basis) throw new Error('DATABASE_URL fehlt (eine Datenbank, deren Benutzer Datenbanken anlegen darf)');
  const { Client } = require('pg');
  const name = `schema_stand_${process.pid}`;
  const admin = new Client({ connectionString: basis });
  await admin.connect();
  await admin.query(`DROP DATABASE IF EXISTS ${name}`);
  await admin.query(`CREATE DATABASE ${name}`);
  const target = new URL(basis);
  target.pathname = '/' + name;
  process.env.DATABASE_URL = target.toString();
  const dbModule = require(path.join(__dirname, '..', 'dist', 'db', 'database.js'));
  const db = dbModule.createDb(dbModule.dbConfigFromEnvironment());
  try {
    await db.initSchemaOnce();
    fs.writeFileSync(DATEI, await schemaText(db));
    console.log(`geschrieben: ${path.relative(process.cwd(), DATEI)}`);
    // The server creates the first account; it does not belong in the base.
    await db.run('DELETE FROM users');
    writeBase(target.toString());
  } finally {
    await db.pool.end().catch(() => {});
    await admin.query(`DROP DATABASE IF EXISTS ${name}`).catch(() => {});
    await admin.end();
  }
}

if (require.main === module)
  main().catch(e => {
    console.error(e.message);
    process.exit(1);
  });

module.exports = { schemaText, writeBase, basisText, pgDumpVersion, DATEI, BASIS };
