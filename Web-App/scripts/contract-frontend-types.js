#!/usr/bin/env node
'use strict';

/**
 * Writes frontend-types/contract.d.ts from docs/openapi-v2.json (API v2): the response
 * of every route as a TypeScript type, so that tsc checks the UI's api() calls
 * against the contract. The file is checked in;
 * test/contract-frontend-types.test.js checks that it matches openapi-v2.json.
 *
 *   npm run contract:frontend
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SOURCE_FILE = path.join(ROOT, 'docs', 'openapi-v2.json');
const TARGET_FILE = path.join(ROOT, 'frontend-types', 'contract.d.ts');

const NAME = /^[A-Za-z_$][\w$]*$/;
const key = (/** @type {string} */ k) => (NAME.test(k) ? k : JSON.stringify(k));

/** A JSON schema as a TypeScript type. @param {any} s @param {string} indent @returns {string} */
function type(s, indent) {
  if (!s || typeof s !== 'object' || Object.keys(s).length === 0) return 'unknown';
  if (s.$ref) return s.$ref.split('/').pop();
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((/** @type {unknown} */ e) => JSON.stringify(e)).join(' | ');
  if (s.anyOf || s.oneOf)
    return [...new Set((s.anyOf || s.oneOf).map((/** @type {any} */ t) => type(t, indent)))].join(' | ');
  if (s.allOf) return s.allOf.map((/** @type {any} */ t) => type(t, indent)).join(' & ');
  if (Array.isArray(s.type))
    return s.type.map((/** @type {string} */ t) => type({ ...s, type: t }, indent)).join(' | ');
  switch (s.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array': {
      const t = type(s.items, indent);
      return /[|&]/.test(t) ? `Array<${t}>` : `${t}[]`;
    }
    case 'object':
      return object(s, indent);
    default:
      return 'unknown';
  }
}

/** @param {any} s @param {string} indent */
function object(s, indent) {
  const inner = indent + '  ';
  const mandatory = new Set(s.required || []);
  const rows = Object.entries(s.properties || {}).map(
    ([k, v]) => `${inner}${key(k)}${mandatory.has(k) ? '' : '?'}: ${type(v, inner)};`,
  );
  // The server passes further fields through (passthrough); they are only read
  // once the contract names them.
  const ap = s.additionalProperties;
  if (ap && !rows.length) return `Record<string, ${type(ap, indent)}>`;
  if (ap) rows.push(`${inner}[feld: string]: unknown;`);
  return rows.length ? `{\n${rows.join('\n')}\n${indent}}` : 'Record<string, never>';
}

/** The content of contract.d.ts. @param {any} doc @returns {string} */
function create(doc) {
  const from = [
    '// Generated by scripts/contract-frontend-types.js from docs/openapi.json — do not edit by hand.',
    '// Regenerate: npm run contract:frontend',
    '',
  ];
  for (const [name, s] of Object.entries(doc.components?.schemas || {}))
    from.push(`export type ${name} = ${type(s, '')};`);
  from.push(
    '',
    '/** Per route: method, path (placeholders as ${string}) and response on success. */',
    'export type Route =',
  );
  const routes = [];
  for (const [path, ops] of Object.entries(doc.paths || {})) {
    const muster = path.replace(/^\/api/, '').replace(/\{[^}]+\}/g, '${string}');
    for (const [method, op] of Object.entries(/** @type {Record<string, any>} */ (ops))) {
      const schema = op.responses?.['200']?.content?.['application/json']?.schema;
      if (!schema) continue;
      const p = muster.includes('${') ? '`' + muster + '`' : `'${muster}'`;
      routes.push(`  | { m: '${method.toUpperCase()}'; p: ${p}; a: ${type(schema, '  ')} }`);
    }
  }
  from.push(...routes.map((z, i) => (i === routes.length - 1 ? z + ';' : z)), '');
  const streams = [];
  for (const [path, ops] of Object.entries(doc.paths || {})) {
    const schema = ops.get?.responses?.['200']?.content?.['text/event-stream']?.schema;
    if (!schema) continue;
    const muster = path.replace(/^\/api/, '').replace(/\{[^}]+\}/g, '${string}');
    const p = muster.includes('${') ? '`' + muster + '`' : `'${muster}'`;
    streams.push(`  | { p: ${p}; e: ${type(schema, '  ')} }`);
  }
  from.push(
    '/** Per event stream (GET): path and one event, as strom() in js/api.js delivers it. */',
    'export type Strom =',
    ...streams.map((z, i) => (i === streams.length - 1 ? z + ';' : z)),
    '',
  );
  return from.join('\n');
}

/** Right away in Biome format, otherwise every rerun would be a format finding. @param {string} text @returns {string} */
function formatted(text) {
  const biome = path.join(ROOT, 'node_modules', '@biomejs', 'biome', 'bin', 'biome');
  const r = require('node:child_process').spawnSync(
    process.execPath,
    [biome, 'format', `--stdin-file-path=${path.relative(ROOT, TARGET_FILE)}`],
    { cwd: ROOT, input: text, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  if (r.status !== 0) throw new Error(`biome format scheiterte (Exit ${r.status}):\n${r.stderr}`);
  return r.stdout;
}

if (require.main === module) {
  fs.writeFileSync(TARGET_FILE, formatted(create(JSON.parse(fs.readFileSync(SOURCE_FILE, 'utf8')))));
  console.log(`geschrieben: ${path.relative(ROOT, TARGET_FILE)}`);
}

module.exports = { SOURCE_FILE, TARGET_FILE, create, formatted };
