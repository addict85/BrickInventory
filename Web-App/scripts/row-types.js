#!/usr/bin/env node
'use strict';
/**
 * Row types from the schema: reads db/schema-stand.sql and writes db/rows.ts. A
 * repository binds its row to it (`Spalten<'price_cache', 'avg_price'>`) instead of guessing the
 * column types anew; NUMERIC arrives as a number (db/database.ts), BIGINT as text.
 * `node scripts/row-types.js --pruefen` only reports whether the file matches the schema.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SCHEMA = path.join(ROOT, 'db', 'schema-stand.sql');
const ZIEL = path.join(ROOT, 'db', 'rows.ts');

/** What node-pg (with the NUMERIC reader from db/database.ts) delivers for a PostgreSQL type. */
/** @type {[RegExp, string][]} */
const JS_TYPE = [
  [/^(integer|smallint|real|double precision|numeric(\(\d+,\d+\))?)$/, 'number'],
  [/^(text|bigint|uuid|character( varying)?(\(\d+\))?)$/, 'string'],
  [/^boolean$/, 'boolean'],
  [/^(timestamp with time zone|timestamp without time zone|date)$/, 'Date'],
  [/^jsonb?$/, 'unknown'],
  [/^bytea$/, 'Buffer'],
];

/** @param {string} pg */
function jsType(pg) {
  const list = pg.endsWith('[]');
  const basis = list ? pg.slice(0, -2) : pg;
  const hits = JS_TYPE.find(([m]) => m.test(basis));
  if (!hits) throw new Error(`Unbekannter Spaltentyp „${pg}“: in scripts/row-types.js eintragen`);
  return list ? `${hits[1]}[]` : hits[1];
}

/** @param {string} sql @returns {Map<string, { name: string, typ: string, null: boolean }[]>} */
function tabellen(sql) {
  /** @type {Map<string, { name: string, typ: string, null: boolean }[]>} */
  const from = new Map();
  for (const m of sql.matchAll(/^CREATE TABLE (\w+) \(\n([\s\S]*?)\n\);/gm)) {
    const columns = [];
    for (const z of (m[2] ?? '').split('\n')) {
      const s = /^ {2}("?[a-z_][a-z0-9_]*"?) (.+?),?$/.exec(z);
      if (!s || /^(CONSTRAINT|PRIMARY|UNIQUE|CHECK|FOREIGN|EXCLUDE)\b/i.test(s[1] ?? '')) continue;
      const rest = s[2] ?? '';
      const typ = rest
        .replace(/ (NOT NULL|DEFAULT|GENERATED|COLLATE|CONSTRAINT)\b.*$/, '')
        .replace(/ (NOT NULL|DEFAULT).*$/, '')
        .trim();
      columns.push({ name: (s[1] ?? '').replace(/"/g, ''), typ, null: !/\bNOT NULL\b/.test(rest) });
    }
    from.set(m[1] ?? '', columns);
  }
  return from;
}

function create() {
  const t = tabellen(fs.readFileSync(SCHEMA, 'utf8'));
  const rows = [
    '// Generated by scripts/row-types.js from db/schema-stand.sql; do not edit by hand.',
    '// Regenerate after every migration: npm run schema:stand && npm run schema:zeilen',
    '',
    '/** Per table the columns as node-pg delivers them (NUMERIC as a number, BIGINT as text). */',
    'export interface Tabellen {',
  ];
  for (const [name, columns] of [...t].sort(([a], [b]) => a.localeCompare(b))) {
    rows.push(`  ${name}: {`);
    for (const s of columns) rows.push(`    ${s.name}: ${jsType(s.typ)}${s.null ? ' | null' : ''};`);
    rows.push('  };');
  }
  rows.push(
    '}',
    '',
    '/** Selected columns of a table: `Spalten<"sets", "user_id" | "set_number">`. */',
    'export type Spalten<T extends keyof Tabellen, S extends keyof Tabellen[T]> = Pick<Tabellen[T], S>;',
    '',
  );
  return rows.join('\n');
}

module.exports = { create, jsType, tabellen, ZIEL };

if (require.main === module) {
  const fresh = create();
  if (process.argv.includes('--pruefen')) {
    const alt = fs.existsSync(ZIEL) ? fs.readFileSync(ZIEL, 'utf8') : '';
    if (alt !== fresh) {
      console.error('[zeilentypen] db/rows.ts passt nicht zum Schema: npm run schema:zeilen');
      process.exit(1);
    }
    console.log('[zeilentypen] db/rows.ts passt zum Schema');
  } else {
    fs.writeFileSync(ZIEL, fresh);
    console.log(`[zeilentypen] ${path.relative(ROOT, ZIEL)} geschrieben`);
  }
}
